create warehouse raktradar_wh with WAREHOUSE_SIZE = 'X-SMALL' AUTO_SUSPEND = 60;
use role accountadmin;

create schema if not exists RAW;
create schema if not exists ANALYTICS;

CREATE ROLE IF NOT EXISTS RAKT_LOADER;
CREATE ROLE IF NOT EXISTS RAKT_TRANSFORMER;
CREATE ROLE IF NOT EXISTS RAKT_REPORTER;

GRANT ROLE RAKT_LOADER TO ROLE SYSADMIN;
GRANT ROLE RAKT_TRANSFORMER TO ROLE SYSADMIN;
GRANT ROLE RAKT_REPORTER TO ROLE SYSADMIN;


GRANT USAGE
ON WAREHOUSE RAKTRADAR_WH
TO ROLE RAKT_LOADER;

GRANT USAGE
ON WAREHOUSE RAKTRADAR_WH
TO ROLE RAKT_TRANSFORMER;

GRANT USAGE
ON WAREHOUSE RAKTRADAR_WH
TO ROLE RAKT_REPORTER;


GRANT USAGE
ON DATABASE RAKTRADAR
TO ROLE RAKT_LOADER;

GRANT USAGE, CREATE STAGE, CREATE TABLE
ON SCHEMA RAKTRADAR.RAW
TO ROLE RAKT_LOADER;

GRANT SELECT, INSERT, UPDATE, DELETE, TRUNCATE
ON ALL TABLES IN SCHEMA RAKTRADAR.RAW
TO ROLE RAKT_LOADER;

GRANT SELECT, INSERT, UPDATE, DELETE, TRUNCATE
ON FUTURE TABLES IN SCHEMA RAKTRADAR.RAW
TO ROLE RAKT_LOADER;

GRANT USAGE
ON DATABASE RAKTRADAR
TO ROLE RAKT_TRANSFORMER;

GRANT USAGE
ON SCHEMA RAKTRADAR.RAW
TO ROLE RAKT_TRANSFORMER;

GRANT SELECT
ON ALL TABLES IN SCHEMA RAKTRADAR.RAW
TO ROLE RAKT_TRANSFORMER;

GRANT SELECT
ON FUTURE TABLES IN SCHEMA RAKTRADAR.RAW
TO ROLE RAKT_TRANSFORMER;

GRANT USAGE, CREATE TABLE, CREATE VIEW
ON SCHEMA RAKTRADAR.ANALYTICS
TO ROLE RAKT_TRANSFORMER;

GRANT SELECT, INSERT, UPDATE, DELETE, TRUNCATE
ON ALL TABLES IN SCHEMA RAKTRADAR.ANALYTICS
TO ROLE RAKT_TRANSFORMER;

GRANT SELECT
ON ALL VIEWS IN SCHEMA RAKTRADAR.ANALYTICS
TO ROLE RAKT_TRANSFORMER;

GRANT SELECT, INSERT, UPDATE, DELETE, TRUNCATE
ON FUTURE TABLES IN SCHEMA RAKTRADAR.ANALYTICS
TO ROLE RAKT_TRANSFORMER;

GRANT SELECT
ON FUTURE VIEWS IN SCHEMA RAKTRADAR.ANALYTICS
TO ROLE RAKT_TRANSFORMER;

-- Reporter: read-only on ANALYTICS
GRANT USAGE ON DATABASE RAKTRADAR TO ROLE RAKT_REPORTER;
GRANT USAGE ON SCHEMA RAKTRADAR.ANALYTICS TO ROLE RAKT_REPORTER;
GRANT SELECT ON ALL TABLES  IN SCHEMA RAKTRADAR.ANALYTICS TO ROLE RAKT_REPORTER;
GRANT SELECT ON ALL VIEWS   IN SCHEMA RAKTRADAR.ANALYTICS TO ROLE RAKT_REPORTER;
GRANT SELECT ON FUTURE TABLES IN SCHEMA RAKTRADAR.ANALYTICS TO ROLE RAKT_REPORTER;
GRANT SELECT ON FUTURE VIEWS  IN SCHEMA RAKTRADAR.ANALYTICS TO ROLE RAKT_REPORTER;

GRANT CREATE FILE FORMAT ON SCHEMA RAKTRADAR.RAW TO ROLE RAKT_LOADER;

-- Internal stage + raw table (owned by the loader)
USE ROLE RAKT_LOADER;
USE WAREHOUSE RAKTRADAR_WH;
USE SCHEMA RAKTRADAR.RAW;

CREATE FILE FORMAT IF NOT EXISTS NDJSON_GZ TYPE = JSON COMPRESSION = GZIP;

CREATE STAGE IF NOT EXISTS RAKT_STAGE FILE_FORMAT = NDJSON_GZ;

CREATE TABLE IF NOT EXISTS BLOOD_STOCK (
    raw_variant  VARIANT,
    _run_id      STRING,
    _source_file STRING,
    _loaded_at   TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);
